import os
import re
import subprocess
import tempfile
import pdfplumber
from app.config import settings

class DocumentParserService:
    """
    文档解析服务，支持 MinerU 深度解析和内置 pdfplumber 高保真表格-文本交织解析
    """
    
    def parse_pdf(self, pdf_path: str) -> str:
        """
        解析 PDF 文件，输出结构化 Markdown。
        """
        if not os.path.exists(pdf_path):
            raise FileNotFoundError(f"PDF file not found: {pdf_path}")
            
        if settings.USE_MINERU:
            try:
                return self._parse_with_mineru(pdf_path)
            except Exception as e:
                # NOTE: MinerU 失败时，自动 fallback 到内置解析器，保证系统的高可用性
                print(f"MinerU parsing failed, falling back to built-in parser. Error: {e}")
                return self._parse_with_fallback(pdf_path)
        else:
            return self._parse_with_fallback(pdf_path)
            
    def _parse_with_mineru(self, pdf_path: str) -> str:
        """
        调用 MinerU 的 magic-pdf 命令行工具进行解析
        """
        with tempfile.TemporaryDirectory() as temp_dir:
            cmd = [
                settings.MINERU_COMMAND,
                "-i", pdf_path,
                "-o", temp_dir,
                "-m", "json"  # 或者是直接提取为 markdown
            ]
            # 运行 magic-pdf 命令
            result = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, check=True)
            
            # 解析输出目录中的 markdown 文件
            # magic-pdf 默认会在输出目录下生成与文件名同名的子目录，里面有 .md 文件
            pdf_name = os.path.splitext(os.path.basename(pdf_path))[0]
            md_dir = os.path.join(temp_dir, pdf_name)
            
            if not os.path.exists(md_dir):
                # 兼容不同版本的 magic-pdf 输出路径结构
                md_dir = temp_dir
                
            md_files = [f for f in os.listdir(md_dir) if f.endswith(".md")]
            if not md_files:
                raise FileNotFoundError("No markdown file generated by MinerU")
                
            md_file_path = os.path.join(md_dir, md_files[0])
            with open(md_file_path, "r", encoding="utf-8") as f:
                return f.read()

    def _parse_with_fallback(self, pdf_path: str) -> str:
        """
        使用内置的 pdfplumber 解析 PDF，提取文本并把表格精准转化为 Markdown Table
        """
        markdown_sections = []
        
        with pdfplumber.open(pdf_path) as pdf:
            for page_idx, page in enumerate(pdf.pages):
                page_text = ""
                
                # 1. 查找页面上的表格并定位它们
                tables = page.find_tables()
                table_bboxes = [t.bbox for t in tables]
                
                # 2. 提取文本，但在提取时可以排除表格区域以避免表格文字混在普通段落中
                # 为简单且高可用，我们分别提取表格和文本。
                # 我们可以先过滤掉表格区域的文本，但更简单有效的方式是提取全页文字，
                # 然后在页面下方追加该页的所有表格，同时用 [Table X] 进行占位。
                raw_text = page.extract_text() or ""
                
                # 清洗多余换行，保持段落连贯
                clean_text = self._clean_text_paragraphs(raw_text)
                
                page_text += f"## Page {page_idx + 1}\n\n"
                page_text += clean_text + "\n\n"
                
                # 3. 处理当前页面的表格
                for idx, t in enumerate(tables):
                    table_data = t.extract()
                    if table_data:
                        markdown_table = self._convert_table_to_markdown(table_data)
                        page_text += f"### 表格 {idx + 1}\n{markdown_table}\n\n"
                        
                markdown_sections.append(page_text)
                
        return "\n---\n\n".join(markdown_sections)
        
    def _convert_table_to_markdown(self, table_data: list[list[str | None]]) -> str:
        """
        将二维数组表格数据转换为 Markdown 表格格式
        """
        if not table_data or not table_data[0]:
            return ""
            
        markdown_lines = []
        
        # 处理表头
        headers = [str(cell or "").replace("\n", " ").strip() for cell in table_data[0]]
        # 确保表头不为空
        headers = [h if h else f"Col {i+1}" for i, h in enumerate(headers)]
        
        markdown_lines.append("| " + " | ".join(headers) + " |")
        markdown_lines.append("| " + " | ".join(["---"] * len(headers)) + " |")
        
        # 处理数据行
        for row in table_data[1:]:
            cells = [str(cell or "").replace("\n", " ").strip() for cell in row]
            # 对齐列数，防止行短缺
            if len(cells) < len(headers):
                cells += [""] * (len(headers) - len(cells))
            else:
                cells = cells[:len(headers)]
            markdown_lines.append("| " + " | ".join(cells) + " |")
            
        return "\n" + "\n".join(markdown_lines) + "\n"
        
    def _clean_text_paragraphs(self, text: str) -> str:
        """
        清洗 PDF 文本换行问题。
        通常 PDF 一行末尾会有多余换行符，此处将不以标点符号结尾的单换行连接起来。
        """
        lines = text.split("\n")
        cleaned_lines = []
        current_paragraph = ""
        
        # 结尾标点符号（判断是否需要另起一段）
        end_punctuation = re.compile(r"[。！？.!?;；：:\"]$")
        
        for line in lines:
            line_str = line.strip()
            if not line_str:
                if current_paragraph:
                    cleaned_lines.append(current_paragraph)
                    current_paragraph = ""
                continue
                
            if current_paragraph:
                # 如果当前段落未结束，拼接
                current_paragraph += line_str
            else:
                current_paragraph = line_str
                
            # 如果行尾有结束标点，或者是段落结束，就推入结果
            if end_punctuation.search(line_str) or len(line_str) < 15:
                cleaned_lines.append(current_paragraph)
                current_paragraph = ""
                
        if current_paragraph:
            cleaned_lines.append(current_paragraph)
            
        return "\n\n".join(cleaned_lines)
        
    def split_into_chunks(self, markdown_text: str, chunk_size: int = 500, chunk_overlap: int = 50) -> list[str]:
        """
        将 Markdown 文本按最大字数以及段落结构进行合理切片
        """
        # 优先以 Page 分割，或以段落 "\n\n" 分割
        paragraphs = re.split(r'\n\n+', markdown_text)
        chunks = []
        current_chunk = ""
        
        for para in paragraphs:
            para = para.strip()
            if not para:
                continue
                
            # 如果单个段落本身就超长，强制按句号切分
            if len(para) > chunk_size:
                sentences = re.split(r'([。！？.!?])', para)
                # 重新拼接句子，确保不超过 chunk_size
                temp_sentence = ""
                for idx in range(0, len(sentences)-1, 2):
                    s = sentences[idx] + (sentences[idx+1] if idx+1 < len(sentences) else "")
                    if len(temp_sentence) + len(s) > chunk_size:
                        if temp_sentence:
                            chunks.append(temp_sentence.strip())
                        temp_sentence = s
                    else:
                        temp_sentence += s
                if temp_sentence:
                    para = temp_sentence
            
            # 正常拼接到 current_chunk
            if len(current_chunk) + len(para) > chunk_size:
                if current_chunk:
                    chunks.append(current_chunk.strip())
                # 考虑 overlap 重叠区
                overlap_start = max(0, len(current_chunk) - chunk_overlap)
                current_chunk = current_chunk[overlap_start:] + "\n\n" + para
            else:
                if current_chunk:
                    current_chunk += "\n\n" + para
                else:
                    current_chunk = para
                    
        if current_chunk:
            chunks.append(current_chunk.strip())
            
        return chunks
